"use client";

import { Loader2, Mic, Save, Trash2, Wand2 } from "lucide-react";
import { useEffect, useState } from "react";
import { Button } from "~/components/ui/button";
import { Textarea } from "~/components/ui/textarea";
import { cn } from "~/lib/utils";

type TranscriptionEditorProps = {
  clipId: string;
  initialTranscript?: string | null;
  transcriptMetadata?: {
    language?: string;
    provider?: string;
    confidence?: number;
  } | null;
  onSave: (transcript: string) => void;
  onAutoTranscribe: () => void;
  onClear: () => void;
  isSaving?: boolean;
  isTranscribing?: boolean;
  disabled?: boolean;
  className?: string;
};

export function TranscriptionEditor({
  clipId,
  initialTranscript,
  transcriptMetadata,
  onSave,
  onAutoTranscribe,
  onClear,
  isSaving = false,
  isTranscribing = false,
  disabled = false,
  className,
}: TranscriptionEditorProps) {
  const [transcript, setTranscript] = useState(initialTranscript ?? "");
  const [isDirty, setIsDirty] = useState(false);

  // Update local state when prop changes
  useEffect(() => {
    setTranscript(initialTranscript ?? "");
    setIsDirty(false);
  }, [initialTranscript, clipId]);

  function handleChange(value: string) {
    setTranscript(value);
    setIsDirty(value !== (initialTranscript ?? ""));
  }

  function handleSave() {
    onSave(transcript);
    setIsDirty(false);
  }

  function handleClear() {
    setTranscript("");
    setIsDirty(false);
    onClear();
  }

  const hasTranscript = transcript.trim().length > 0;
  const isAutoGenerated = transcriptMetadata?.provider === "whisper";
  const isManual = transcriptMetadata?.provider === "manual";
  const isPending =
    transcriptMetadata?.provider === "whisper" &&
    transcriptMetadata?.confidence === 0;

  return (
    <div className={cn("space-y-2", className)}>
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2">
          <Mic className="h-4 w-4 text-muted-foreground" />
          <span className="font-medium text-sm">Transcription</span>
          {transcriptMetadata && (
            <span className="text-muted-foreground text-xs">
              {isManual && "(Manual)"}
              {isAutoGenerated && !isPending && "(Auto)"}
              {isPending && "(Pending API)"}
            </span>
          )}
        </div>

        <div className="flex items-center gap-1">
          {!hasTranscript && (
            <Button
              disabled={disabled || isTranscribing}
              onClick={onAutoTranscribe}
              size="sm"
              title="Auto-transcribe using AI"
              variant="ghost"
            >
              {isTranscribing ? (
                <Loader2 className="h-3.5 w-3.5 animate-spin" />
              ) : (
                <Wand2 className="h-3.5 w-3.5" />
              )}
              <span className="sr-only md:not-sr-only">Auto</span>
            </Button>
          )}

          {isDirty && (
            <Button
              disabled={disabled || isSaving}
              onClick={handleSave}
              size="sm"
              variant="ghost"
            >
              {isSaving ? (
                <Loader2 className="h-3.5 w-3.5 animate-spin" />
              ) : (
                <Save className="h-3.5 w-3.5" />
              )}
              <span className="sr-only md:not-sr-only">Save</span>
            </Button>
          )}

          {hasTranscript && (
            <Button
              disabled={disabled || isSaving || isTranscribing}
              onClick={handleClear}
              size="sm"
              title="Clear transcription"
              variant="ghost"
            >
              <Trash2 className="h-3.5 w-3.5" />
              <span className="sr-only">Clear</span>
            </Button>
          )}
        </div>
      </div>

      <Textarea
        className={cn(
          "min-h-[60px] resize-y text-sm",
          isDirty && "border-primary/50"
        )}
        disabled={disabled || isTranscribing}
        onChange={(e) => handleChange(e.target.value)}
        placeholder="Enter or auto-generate transcription..."
        rows={3}
        value={transcript}
      />

      {transcriptMetadata?.confidence !== undefined &&
        transcriptMetadata.confidence > 0 && (
          <div className="flex items-center justify-between text-xs">
            <span className="text-muted-foreground">
              Confidence: {(transcriptMetadata.confidence * 100).toFixed(0)}%
            </span>
            {transcriptMetadata.language && (
              <span className="text-muted-foreground">
                Language: {transcriptMetadata.language.toUpperCase()}
              </span>
            )}
          </div>
        )}
    </div>
  );
}

/**
 * Compact transcription display for list views
 */
type TranscriptionPreviewProps = {
  transcript?: string | null;
  maxLength?: number;
  className?: string;
};

export function TranscriptionPreview({
  transcript,
  maxLength = 100,
  className,
}: TranscriptionPreviewProps) {
  if (!transcript) {
    return (
      <p className={cn("text-muted-foreground text-xs italic", className)}>
        No transcription
      </p>
    );
  }

  const truncated =
    transcript.length > maxLength
      ? `${transcript.slice(0, maxLength)}...`
      : transcript;

  return (
    <p
      className={cn("text-sm", className)}
      title={transcript.length > maxLength ? transcript : undefined}
    >
      "{truncated}"
    </p>
  );
}
